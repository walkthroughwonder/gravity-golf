// Generate from the game's canonical solver, so worker and file-preview math cannot drift.
export function aimSolverSource(source) {
  const start = 'function simulateShot(startPos, launchDir, power, maxSteps) {';
  const end = 'async function toggleOptimalPath() {';
  if (source.split(start).length !== 2 || source.split(end).length !== 2) {
    throw new Error('Aim solver source contract changed');
  }
  const code = source.slice(source.indexOf(start), source.indexOf(end));
  if (!code.includes('function findOptimalPath() {')) throw new Error('Missing aim solver');
  return code;
}

export function buildAimWorker(source, threeImport) {
  return `// Generated by scripts/build-aim-worker.mjs. Do not edit.
import * as THREE from ${JSON.stringify(threeImport)};
self.onmessage = ({ data: { id, snapshot } }) => {
  try {
    const vector = xyz => new THREE.Vector3().fromArray(xyz);
    const planetoids = snapshot.planetoids.map(p => ({ ...p, pos: vector(p.pos) }));
    const ball = { position: vector(snapshot.startPos) };
    const ballOnPlanet = planetoids[snapshot.planetIndex];
    const homePlanet = planetoids[snapshot.homeIndex];
    const goalPlanet = planetoids[snapshot.goalIndex];
    const holePos = vector(snapshot.holePos);
    const { ballRadius, levelPowerMult, SURFACE_FRICTION, CAPTURE_SPEED, MAX_DIST } = snapshot;
${aimSolverSource(source)}
    self.postMessage({ id, result: findOptimalPath() });
  } catch {
    self.postMessage({ id, error: 'Aim calculation failed' });
  }
};
`;
}
